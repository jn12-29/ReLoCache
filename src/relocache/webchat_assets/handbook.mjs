九、费用预算与项目归属
所有出差费用必须绑定已经批准的项目编号。行政团队负责确认出差事由与项目的关联，财务团队负责确认费用科目、预算余额及支付状态。项目负责人不等同于部门负责人，也不自动拥有财务审批权限。同一人同时兼任多个角色时，系统保留各审批节点的独立记录。任何人不得审批自己的报销；本人为项目负责人时，项目确认节点由上一级负责人代签。
